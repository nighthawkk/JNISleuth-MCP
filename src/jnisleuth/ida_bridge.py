from pathlib import Path
import shutil
import subprocess
from typing import Any

from .ghidra_bridge import normalize_bindings_input
from .vtable_analyzer import (
    JAVAVM_INVOKE_INTERFACE_ENTRIES,
    JNI_NATIVE_INTERFACE_ENTRIES,
)


def generate_ida_jni_c_header() -> str:
    """Generates a self-contained C header defining JNIEnv*, JavaVM*, and JNINativeMethod for IDA `idc_parse_types`."""
    lines = [
        "/* Auto-generated by JNISleuth-MCP for IDA Pro 9.0 Local Types (til) */",
        "typedef unsigned char jboolean;",
        "typedef signed char jbyte;",
        "typedef unsigned short jchar;",
        "typedef short jshort;",
        "typedef int jint;",
        "typedef jint jsize;",
        "typedef long long jlong;",
        "typedef float jfloat;",
        "typedef double jdouble;",
        "typedef void *jobject;",
        "typedef jobject jclass;",
        "typedef jobject jstring;",
        "typedef jobject jarray;",
        "typedef jarray jobjectArray;",
        "typedef jarray jbooleanArray;",
        "typedef jarray jbyteArray;",
        "typedef jarray jcharArray;",
        "typedef jarray jshortArray;",
        "typedef jarray jintArray;",
        "typedef jarray jlongArray;",
        "typedef jarray jfloatArray;",
        "typedef jarray jdoubleArray;",
        "typedef jobject jthrowable;",
        "typedef jobject jweak;",
        "typedef void *jfieldID;",
        "typedef void *jmethodID;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const char *signature;",
        "    void *fnPtr;",
        "} JNINativeMethod;",
        "",
        "struct JNINativeInterface_;",
        "typedef const struct JNINativeInterface_ *JNIEnv;",
        "struct JNIInvokeInterface_;",
        "typedef const struct JNIInvokeInterface_ *JavaVM;",
        "",
        "struct JNINativeInterface_ {",
    ]

    for idx, (slot_name, proto) in enumerate(JNI_NATIVE_INTERFACE_ENTRIES):
        open_p = proto.find("(")
        if open_p != -1:
            ret_type = proto[:open_p].strip()
            params = proto[open_p:]
            lines.append(f"    {ret_type} (*{slot_name}){params}; /* +0x{idx * 8:03x} */")
        else:
            lines.append(f"    void *reserved_{idx}; /* +0x{idx * 8:03x} ({slot_name}) */")

    lines.extend(
        [
            "};",
            "",
            "struct JNIInvokeInterface_ {",
        ]
    )

    for idx, (slot_name, proto) in enumerate(JAVAVM_INVOKE_INTERFACE_ENTRIES):
        open_p = proto.find("(")
        if open_p != -1:
            ret_type = proto[:open_p].strip()
            params = proto[open_p:]
            lines.append(f"    {ret_type} (*{slot_name}){params}; /* +0x{idx * 8:03x} */")
        else:
            lines.append(f"    void *invoke_reserved_{idx}; /* +0x{idx * 8:03x} ({slot_name}) */")

    lines.append("};")
    return "\n".join(lines) + "\n"


def detect_ida9_environment() -> dict[str, Any]:
    """Detects IDA Pro 9.0+ `idalib` (`idapro` Python module), `idapyswitch`, and headless `idat64`."""
    ida_dir = os.environ.get("IDA_INSTALL_DIR") or os.environ.get("IDADIR") or ""
    has_idalib = importlib.util.find_spec("idapro") is not None

    idapyswitch_bin = shutil.which("idapyswitch")
    idat64_bin = shutil.which("idat64") or shutil.which("idat")

    if ida_dir:
        ida_path = Path(ida_dir)
        for cand in (ida_path / "idapyswitch", ida_path / "idapyswitch.exe"):
            if cand.exists():
                idapyswitch_bin = str(cand)
                break
        for cand in (ida_path / "idat64", ida_path / "idat", ida_path / "ida64"):
            if cand.exists():
                idat64_bin = str(cand)
                break

    preferred_backend = (
        "idalib-9.0"
        if has_idalib
        else ("idat64-cli" if idat64_bin else "manifest-ready (offline)")
    )
    return {
        "ida_install_dir": ida_dir or None,
        "has_idalib_python": has_idalib,
        "idapyswitch_path": idapyswitch_bin,
        "idat_binary_path": idat64_bin,
        "preferred_backend": preferred_backend,
    }


def sync_ida_jni_types(
    trace_json: str | Path | dict[str, Any] | list[Any],
    database_name: str = "banker_dropper.i64",
    output_manifest_path: str | Path | None = None,
    output_header_path: str | Path | None = None,
    ollvm_branches: list[dict[str, Any]] | None = None,
    run_headless: bool = False,
    binary_path: str | Path | None = None,
) -> dict[str, Any]:
    """Synchronizes JNIEnv*, JavaVM*, JNINativeMethod, function prototypes, and OLLVM xrefs to IDA Pro 9.0."""
    functions = normalize_bindings_input(trace_json)
    c_header = generate_ida_jni_c_header()
    env_info = detect_ida9_environment()

    script_dir = Path(__file__).resolve().parents[2] / "ida_scripts"
    resolve_script = script_dir / "ResolveJNIBridge_IDA.py"

    manifest: dict[str, Any] = {
        "database_name": database_name,
        "ida_script": str(resolve_script),
        "backend": env_info["preferred_backend"],
        "jni_vtable_slots": len(JNI_NATIVE_INTERFACE_ENTRIES),
        "javavm_vtable_slots": len(JAVAVM_INVOKE_INTERFACE_ENTRIES),
        "synced_function_count": len(functions),
        "ollvm_indirect_branch_count": len(ollvm_branches or []),
        "jni_c_header": c_header,
        "functions": functions,
        "ollvm_indirect_branches": ollvm_branches or [],
    }

    if output_manifest_path is not None:
        out_p = Path(output_manifest_path)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    if output_header_path is not None:
        hdr_p = Path(output_header_path)
        hdr_p.parent.mkdir(parents=True, exist_ok=True)
        hdr_p.write_text(c_header, encoding="utf-8")

    headless_executed = False
    execution_mode = env_info["preferred_backend"]

    if run_headless and binary_path:
        if env_info["has_idalib_python"]:
            try:
                import idapro  # type: ignore

                sys_path_added = False
                if str(script_dir) not in os.sys.path:
                    os.sys.path.insert(0, str(script_dir))
                    sys_path_added = True
                try:
                    import ResolveJNIBridge_IDA  # type: ignore

                    idapro.open_database(str(binary_path), run_auto_analysis=True)
                    ResolveJNIBridge_IDA.apply_manifest_in_ida(manifest)
                    idapro.close_database(save=True)
                    headless_executed = True
                    execution_mode = "idalib-9.0 (in-process)"
                finally:
                    if sys_path_added:
                        os.sys.path.remove(str(script_dir))
            except Exception:
                headless_executed = False

        elif env_info["idat_binary_path"]:
            manifest_tmp = Path(output_manifest_path or "/tmp/jnisleuth_ida_sync.json")
            manifest_tmp.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
            cmd = [
                str(env_info["idat_binary_path"]),
                "-A",
                f'-S"{resolve_script} {manifest_tmp}"',
                str(binary_path),
            ]
            try:
                subprocess.run(cmd, check=True, capture_output=True, text=True, timeout=120)
                headless_executed = True
                execution_mode = "idat64-cli"
            except (subprocess.SubprocessError, OSError):
                headless_executed = False

    return {
        "status": "synced",
        "database_name": database_name,
        "backend": execution_mode,
        "ida_environment": env_info,
        "synced_function_count": len(functions),
        "ollvm_indirect_branch_count": len(ollvm_branches or []),
        "jni_vtable_slots_applied": len(JNI_NATIVE_INTERFACE_ENTRIES),
        "javavm_vtable_slots_applied": len(JAVAVM_INVOKE_INTERFACE_ENTRIES),
        "ida_script": str(resolve_script),
        "headless_executed": headless_executed,
        "functions": functions,
    }
